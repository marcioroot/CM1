window.CM1_DATA.getWordInfo = function(word) {
  if (!word) return null;
  const w = word.toLowerCase().trim();
  if (window.CM1_DATA.variations[w]) {
    return { baseWord: w, isBase: true, ...window.CM1_DATA.variations[w] };
  }
  if (window.CM1_DATA.reverseIndex[w]) {
    const rev = window.CM1_DATA.reverseIndex[w];
    return { baseWord: rev.baseWord, isBase: false, formType: rev.type, ...(window.CM1_DATA.variations[rev.baseWord] || {}) };
  }
  return null;
};
